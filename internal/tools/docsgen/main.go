// Command docsgen writes the reference pages of stormbreaker's packs, and the index of their steps,
// from the packs themselves: the docs site's build runs it (docs/scripts/gen.mjs), so the
// reference cannot drift from the code.
//
//	go run ./internal/tools/docsgen -out docs/src/content/docs/references/_gen
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nimbusxr/axx/core"

	sbcore "github.com/nimbusxr/stormbreaker/packs/core"
	sbkafka "github.com/nimbusxr/stormbreaker/packs/kafka"
	sbprometheus "github.com/nimbusxr/stormbreaker/packs/prometheus"
	sbrest "github.com/nimbusxr/stormbreaker/packs/rest"
)

type pack struct {
	path string // the package's path in the module
	pack core.Pack
}

var packs = []pack{
	{"packs/core", sbcore.Pack()},
	{"packs/rest", sbrest.Pack()},
	{"packs/kafka", sbkafka.Pack()},
	{"packs/prometheus", sbprometheus.Pack()},
}

const banner = "<!-- Code generated by go run ./internal/tools/docsgen. DO NOT EDIT. -->\n\n"

func main() {
	out := flag.String("out", "docs/src/content/docs/references/_gen", "where the pages go")
	flag.Parse()
	if err := os.MkdirAll(filepath.Join(*out, "packs"), 0o755); err != nil {
		fail(err)
	}
	var index strings.Builder
	index.WriteString("---\nslug: \"references/step-index\"\ntitle: Step index\ndescription: \"Every step of stormbreaker's packs, on one page.\"\n---\n\n")
	index.WriteString(banner)
	index.WriteString("Every step of stormbreaker's packs, one per line: `pack | id | expression`. `{name}` is a parameter, " +
		"`[[...]]` are optional words, and `[+table | ... |]` is a step's data table. A step is public API: its text never changes " +
		"by accident. Search this list instead of inventing step text; with axx installed, `axx steps` lists a project's steps and " +
		"`axx steps show <id>` documents one. axx's own steps, which stormbreaker's scenarios use too, are at " +
		"[axx.nimbusxr.us](https://axx.nimbusxr.us/references/step-index/).\n\n```text\n")
	var pages []string
	for _, p := range packs {
		m := p.pack.Manifest()
		if err := os.WriteFile(filepath.Join(*out, "packs", m.Name+".md"), []byte(page(p.path, m)), 0o644); err != nil {
			fail(err)
		}
		pages = append(pages, fmt.Sprintf("[%s](/references/packs/%s/)", m.Name, m.Name))
		for _, s := range m.Steps {
			fmt.Fprintf(&index, "%s | %s | %s%s\n", m.Name, s.ID, s.Expr, argument(s))
		}
	}
	index.WriteString("```\n\nEach pack's page documents its steps: " + strings.Join(pages, ", ") + ".\n")
	if err := os.WriteFile(filepath.Join(*out, "step-index.md"), []byte(index.String()), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "docsgen:", err)
	os.Exit(1)
}

func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// argument says what a step takes besides its text, for its line in the step index.
func argument(s core.StepDef) string {
	switch s.Arg {
	case core.ArgTable:
		if s.Table != nil && len(s.Table.Columns) > 0 {
			return "  [+table | " + strings.Join(s.Table.Columns, " | ") + " |]"
		}
		return "  [+table]"
	case core.ArgDocString:
		return "  [+docstring]"
	}
	return ""
}

func firstSentence(doc string) string {
	line := strings.SplitN(doc, "\n", 2)[0]
	if i := strings.Index(line, ". "); i > 0 {
		line = line[:i+1]
	}
	return strings.ReplaceAll(line, "`", "")
}

func page(path string, m core.Manifest) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\nslug: %q\ntitle: %s\ndescription: %q\n---\n\n", "references/packs/"+m.Name, m.Name, firstSentence(m.Doc))
	b.WriteString(banner)
	b.WriteString(m.Doc + "\n\n")
	fmt.Fprintf(&b, "## Add it\n\nList it in the project's `axx-packs.yaml`, with the packs it builds on:\n\n```yaml title=\"axx-packs.yaml\"\npacks:\n")
	for _, r := range m.Requires {
		fmt.Fprintf(&b, "  - %s\n", r)
	}
	if m.Name != sbcore.Name {
		b.WriteString("  - github.com/nimbusxr/stormbreaker/packs/core@v0.1.0\n")
	}
	fmt.Fprintf(&b, "  - github.com/nimbusxr/stormbreaker/%s@v0.1.0\n```\n\n", path)
	if len(m.ConfigSchema) > 0 {
		var schema struct {
			Properties map[string]struct {
				Type        string   `json:"type"`
				Enum        []string `json:"enum"`
				Description string   `json:"description"`
			} `json:"properties"`
			Required []string `json:"required"`
		}
		if err := json.Unmarshal(m.ConfigSchema, &schema); err == nil && len(schema.Properties) > 0 {
			fmt.Fprintf(&b, "## Settings\n\nIn `axx.yaml`, under `packs.%s`:\n\n| Setting | What it is |\n|---|---|\n", m.Name)
			names := make([]string, 0, len(schema.Properties))
			for n := range schema.Properties {
				names = append(names, n)
			}
			sort.Strings(names)
			for _, n := range names {
				p := schema.Properties[n]
				req := ""
				for _, r := range schema.Required {
					if r == n {
						req = " (required)"
					}
				}
				fmt.Fprintf(&b, "| `%s`%s | %s |\n", n, req, cell(p.Description))
			}
			b.WriteString("\n")
		}
	}
	if len(m.Params) > 0 {
		b.WriteString("## Parameter types\n\n| Parameter | What it takes | Examples |\n|---|---|---|\n")
		for _, p := range m.Params {
			ex := make([]string, len(p.Examples))
			for i, e := range p.Examples {
				ex[i] = "`" + e + "`"
			}
			fmt.Fprintf(&b, "| `{%s}` | %s | %s |\n", p.Name, cell(p.Doc), strings.Join(ex, ", "))
		}
		b.WriteString("\n")
	}
	if len(m.Hooks) > 0 {
		b.WriteString("## Hooks\n\nThe pack runs these around the scenarios and steps of every suite that lists it:\n\n")
		for _, h := range m.Hooks {
			fmt.Fprintf(&b, "- `%s` (%s)\n", h.ID, h.Phase)
		}
		b.WriteString("\n")
	}
	if len(m.Steps) > 0 {
		b.WriteString("## Steps\n\n")
	}
	for _, s := range m.Steps {
		fmt.Fprintf(&b, "### `%s`\n\n```gherkin\n%s %s\n```\n\n%s\n\n", s.ID, s.Keyword, s.Expr, s.Doc)
		if s.Table != nil && len(s.Table.Rows) > 0 {
			b.WriteString("| Property | Takes | Default |\n|---|---|---|\n")
			for _, r := range s.Table.Rows {
				name := "`" + r.Name + "`"
				if r.Required {
					name += " (required)"
				}
				fmt.Fprintf(&b, "| %s | %s | %s |\n", name, cell(r.Takes), cell(r.Default))
			}
			b.WriteString("\n")
		}
		if len(s.Examples) > 0 {
			b.WriteString("```gherkin\n" + strings.Join(s.Examples, "\n") + "\n```\n\n")
		}
	}
	return b.String()
}
